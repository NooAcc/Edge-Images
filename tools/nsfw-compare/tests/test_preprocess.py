"""Preprocessing must reproduce the Go/server pipeline byte-for-byte.

The golden file is the same one the Go tests use, generated by
tools/nsfw-model/verify.py from the upstream EfficientNetImageProcessorPil.
"""

from __future__ import annotations

import json
import unittest
from pathlib import Path

import numpy as np
from PIL import Image

from nsfw_compare.preprocess import ModelInputSize, nearest_indices, preprocess_image

ROOT = Path(__file__).resolve().parents[3]
GOLDEN = ROOT / "internal" / "nsfw" / "testdata" / "preprocess_golden.json"


def make_image(width: int, height: int) -> Image.Image:
    data = bytearray(width * height * 3)
    for y in range(height):
        for x in range(width):
            offset = (y * width + x) * 3
            for c in range(3):
                data[offset + c] = (x * 7 + y * 13 + c * 29) & 0xFF
    return Image.frombytes("RGB", (width, height), bytes(data))


class PreprocessGoldenTest(unittest.TestCase):
    def test_matches_golden_cases(self) -> None:
        golden = json.loads(GOLDEN.read_text(encoding="utf-8"))
        self.assertEqual(golden["inputSize"], ModelInputSize)

        for case in golden["cases"]:
            with self.subTest(case=case["name"]):
                image = make_image(case["width"], case["height"])
                tensor = preprocess_image(image)
                self.assertEqual(tensor.shape, (1, 3, ModelInputSize, ModelInputSize))
                self.assertEqual(tensor.dtype, np.float32)
                flat = tensor.reshape(-1)
                for sample in case["samples"]:
                    self.assertAlmostEqual(
                        float(flat[sample["index"]]),
                        sample["value"],
                        places=5,
                        msg=f"case={case['name']} index={sample['index']}",
                    )

    def test_tensor_is_nchw_not_nhwc(self) -> None:
        # A one-pixel-wide image makes channel placement obvious: the three
        # channel planes must carry different values.
        image = Image.new("RGB", (1, 1), (255, 0, 0))
        tensor = preprocess_image(image).reshape(3, -1)
        self.assertGreater(float(tensor[0, 0]), float(tensor[1, 0]))
        self.assertNotAlmostEqual(float(tensor[1, 0]), float(tensor[2, 0]), places=4)


class NearestIndicesTest(unittest.TestCase):
    def test_upscale_repeats_source_pixels(self) -> None:
        self.assertEqual(nearest_indices(1, 4), [0, 0, 0, 0])

    def test_downscale_uses_pillow_centres(self) -> None:
        # Pillow picks the pixel whose centre contains the sample point.
        self.assertEqual(nearest_indices(4, 2), [1, 3])
        self.assertEqual(nearest_indices(7, 3), [1, 3, 5])

    def test_clamps_to_source_bounds(self) -> None:
        indices = nearest_indices(3, 7)
        self.assertTrue(all(0 <= i < 3 for i in indices))
        self.assertEqual(indices[-1], 2)


if __name__ == "__main__":
    unittest.main()
